import { IdentitasModul } from "../types";

export const getKotaSekolah = (identitas: IdentitasModul): string => {
  if (identitas.kotaSekolah && identitas.kotaSekolah.trim()) {
    return identitas.kotaSekolah.trim();
  }

  const namaSekolah = identitas.namaSekolah || "";
  
  // Match common Indonesian city/regency names
  const match = namaSekolah.match(
    /(?:PEMATANGSIANTAR|PEMATANG SIANTAR|JAKARTA|MEDAN|BANDUNG|SURABAYA|SEMARANG|YOGYAKARTA|PALEMBANG|MAKASSAR|DENPASAR|BOGOR|BEKASI|TANGERANG|DEPOK|PADANG|PEKANBARU|BATAM|BALIKPAPAN|SAMARINDA|BANJARMASIN|MANADO|AMBON|JAYAPURA|SURAKARTA|SOLO|MALANG|KEDIRI|BLITAR|MAGELANG|SALATIGA|TEGAL|CIREBON|SUKABUMI|TASIKMALAYA|CIMAHI|PROBOLINGGO|PASURUAN|MOJOKERTO|BANYUWANGI|JEMBER|MADIUN|PONOROGO|TULUNGAGUNG|LUMAJANG|BONDOWOSO|SIDOARJO|GRESIK|LAMONGAN|TUBAN|BOJONEGORO|NGAWI|MAGETAN|CARUBAN|NGANJUK|PACITAN|TRENGGALEK|SAMPANG|PAMEKASAN|SUMENEP|BANGKALAN|LANGSA|LHOKSEUMAWE|BANDA ACEH|SABANG|SUBULUSSALAM|MEULABOH|TAKENGON|SIGLI|BIREUEN|TAPAKTUAN|KUTACANE|BINJAI|TEBING TINGGI|TANJUNG BALAI|SIBOLGA|PADANG SIDEMPUAN|GUNUNGSITOLI|KABANJAHE|BERASTAGI|TARUTUNG|BALIGE|SALAK|STABAT|LUBUK PAKAM|SEI RAMPAH|RAYA|PANYABUNGAN|KOTA AGUNG|BATU BARA|LABUHANBATU|RANTAU PRAPAT|KISARAN|PERBAUNGAN|DOLOK SULIT|INDRA PURA|LIMAPULUH|DUMAI|BANGKINANG|RENGAT|TEMBILAHAN|TELUK KUANTAN|PANGKALAN KERINCI|MAMUJU|PALU|GORONTALO|KENDARI|PALOPO|PAREPARE|BAUBAU|BITUNG|TOMOHON|KOTAMOBAGU|TOLITOLI|POSO|LUWUK|TAUNA|SORONG|MANOKWARI|MERAUKE|TIMIKA|BIAK|NABIRE|FAKFAK|AGATS|WAMENA|TANAH MERAH|SERUI|RANSIKI|KAPUAS|PALANGKARAYA|SAMPIT|PANGKALAN BUN|MUARA TEWEH|BUNTOK|KASONGAN|NANGA BULIK|PURUK CAHU|KUALA KAPUAS|TAMIANG LAYANG|SUKAMARA|BONTANG|TENGGARONG|SANGATTA|TANJUNG REDEB|SENDAWAR|PENAJAM|TANAH GROGOT|TARAKAN|TANJUNG SELOR|NUNUKAN|MALINAU|BANJARBARU|MARTAPURA|PELAIHARI|BATULICIN|KOTABARU|RANTAU|KANDANGAN|BARABAI|AMUNTAI|PARINGIN|MARABAHAN|TANJUNG|PONTIANAK|SINGKAWANG|SAMBAS|MEMPAWAH|KETAPANG|SINTANG|SANGGAU|SEKADAU|PUTUSSIBAU|NANGA PINOH|BENGKAYANG|LANDAK|SUKADANA|KUPANG|ENDE|MAUMERE|ROTE|ATAMBUA|SOE|KEFAMENANU|WAINGAPU|WAIKABUBAK|RUTENG|BORONG|BAJAWA|MBAY|LABUAN BAJO|KALABAHI|LEWOLEBA|LARANTUKA|SINGARAJA|TABANAN|GIANYAR|KLUNGKUNG|BANGLI|AMLAPURA|NEGARA|SENGGIGI|MATARAM|PRAYA|SELONG|SUMBAWA|DOMPU|BIMA|TALIWANG)/i
  );

  if (match) {
    const raw = match[0].trim();
    // Normalize casing (e.g. PEMATANGSIANTAR -> Pematangsiantar)
    return raw
      .split(/\s+/)
      .map((word) => word.charAt(0).toUpperCase() + word.slice(1).toLowerCase())
      .join(" ");
  }

  // Fallback to last meaningful word of namaSekolah
  const words = namaSekolah.trim().split(/\s+/);
  const lastWord = words[words.length - 1];
  if (
    lastWord &&
    lastWord.length > 2 &&
    !/^(1|2|3|4|5|6|7|8|9|0|SD|SMP|SMA|SMK|MI|MTS|MA|STATE|NEGERI|UPTD|UPT)$/i.test(lastWord)
  ) {
    return lastWord.charAt(0).toUpperCase() + lastWord.slice(1).toLowerCase();
  }

  return "Pematangsiantar";
};

export const getKotaDanTanggal = (identitas: IdentitasModul): string => {
  const tgl = identitas.tanggalDokumen || "................... 2026";
  // If tanggalDokumen already includes a comma (e.g. "Pematangsiantar, 28 Juli 2026"), return as is
  if (tgl.includes(",")) {
    return tgl;
  }
  const kota = getKotaSekolah(identitas);
  return `${kota}, ${tgl}`;
};
